def fault_rule_policies(bundle: Bundle) -> set[str]:
    """Names of the policies a FaultRule or DefaultFaultRule of any endpoint runs."""
    found: set[str] = set()
    endpoints: list[ProxyEndpoint | TargetEndpoint] = [*bundle.proxy_endpoints, *bundle.target_endpoints]
    for endpoint in endpoints:
        for rule in endpoint.fault_rules:
            found.update(step.policy for step in rule.steps)
        if endpoint.default_fault_rule is not None:
            found.update(step.policy for step in endpoint.default_fault_rule.steps)
    return found


def recorded_key_properties(
    bundle: Bundle, app_dir: Path, recorded: Iterable[tuple[HttpRequest, int]]
) -> tuple[dict[str, str], tuple[str, ...]]:
    """Settings that allow, in the deployed copy only, the API keys a golden recording shows as valid.

    For each VerifyAPIKey whose allowed-keys property in the generated properties file is empty, the
    key each recorded request presented where the policy reads it (header or query parameter) counts
    as valid when Apigee's recorded answer was not 401. Returns the settings and a note per policy for
    the report (the keys themselves are never written into the note).
    """
    props = read_properties(app_dir)
    calls = list(recorded)
    settings: dict[str, str] = {}
    notes: list[str] = []
    for policy in bundle.policies:
        if policy.type != "VerifyAPIKey" or not policy.enabled:
            continue
        prop = f"verifyapikey.{key_part(policy.name)}.allowedKeys"
        if prop not in props or any(k.strip() for k in props[prop].split(",")):
            continue
        ref = _api_key_ref(policy)
        keys: list[str] = []
        for request, status in calls:
            if status == 401:
                continue
            value = _request_value(request, ref)
            if value and "," not in value and value not in keys:
                keys.append(value)
        if keys:
            settings[prop] = ",".join(keys)
            notes.append(
                f"VerifyAPIKey {policy.name} has no allowed key in {PROPERTIES_PATH[-1]}, so the replay allowed the "
                f"{len(keys)} key(s) the recorded requests presented with a non-401 answer, in the deployed copy only"
            )
    return settings, tuple(notes)


def _request_value(request: HttpRequest, ref: str) -> str | None:
    """The value ``ref`` (request.header.X or request.queryparam.X) reads from ``request``, as VerifyAPIKey reads it."""
    folded = fold(ref.strip())
    if folded.startswith("request.header.") and folded.count(".") == 2:
        name = fold(ref.strip().split(".", 2)[2])
        value = next((v for k, v in dict(request.headers).items() if fold(str(k)) == name), None)
        return value.split(",", 1)[0].strip() if value is not None else None
    if folded.startswith("request.queryparam.") and folded.count(".") == 2:
        name = ref.strip().split(".", 2)[2]
        values = parse_qs(urlsplit(request.path).query, keep_blank_values=True).get(name)
        return values[0] if values else None
    return None

"""Per-policy test batteries: the requests to send a proxy's Mule app, and what Apigee would answer.

:func:`build_battery` reads the proxy's IR and its generated project and
returns one or more cases per policy a2m can test, each a short series of
calls with the expected status of every call, the number of calls the mock
backend must receive and the headers those calls must (or must not) carry.
Expectations come from the proxy's own policies (:mod:`a2m.verify.sim`),
never from the generated app, so the battery checks the app against Apigee's
behaviour. Limits and names come from the proxy's settings: the rate of a
SpikeArrest, the allowance of a Quota, where a VerifyAPIKey reads its key.

Situations per policy type:

* SpikeArrest: under-limit, over-limit (N calls spaced by the pace interval
  pass, one more sent right away gets 429);
* Quota: within-allowance, over-allowance (the allowance plus one call);
* VerifyAPIKey: valid-key, missing-key, bad-key; the valid key is the first
  allowed key in the generated properties file, or a test key the runner sets
  in the deployed copy when that list is empty;
* AssignMessage: header-set (only when no other case already checks the
  headers it sets on the backend call), condition-false (its step's condition
  is false, so the header is not set);
* ExtractVariables: extracted-value-used (a value it extracts reaches the
  backend through a later step; only when no other case already shows it);
* RaiseFault: fault-raised; BasicAuthentication (Decode): correct-credentials,
  missing-credentials; AccessControl: denied-address or allowed-address for
  the local test address; ResponseCache: repeated-call-cached (three
  identical calls, one backend hit), once a2m generates it.

Cases exist only for steps a2m generated and that run in the app, decided
from the generator's own per-step records (:mod:`a2m.verify.generated`), never
from the policy type: a step a2m did not generate (ResponseCache, which has no
Mule template yet, a template that skipped the step with the request changes
made before it, ...) or generated where it never runs (its condition, or the
condition of its Flow or RouteRule, can't be translated, so its ``when`` is
``#[false]``) is listed as untested with the reason "not generated by a2m",
never run as a case the app can only fail. When a policy has several steps,
the first one that runs in the app is tested. A case whose request, in Apigee,
runs another step the app does not run (not generated, or never runs there) is
untested too: what Apigee does for it is not what the app was made to do.

Whatever cannot be tested is listed in :attr:`Battery.untested` with the
reason, so every policy of the proxy has at least one case or an entry there.
A case whose expected answer is an error while the endpoint has a FaultRule or
DefaultFaultRule is untested too: those rules may change the error response,
and a2m does not simulate them (:mod:`a2m.verify.sim`).

:func:`recorded_key_properties` does for a golden replay what the battery does
with its test key: when a VerifyAPIKey's allowed-keys property is empty, the
keys the recorded requests presented (and Apigee did not answer 401) are
allowed in the deployed copy only.
"""

